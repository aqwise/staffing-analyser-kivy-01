from staffing_chainable_agents_request_pipeline.utils import DEFAULT_DOMAINS


def attractiveness_profiler_prompt(business_domain=DEFAULT_DOMAINS):
    prompt_text = f"""
    Контекст: Ты AI‑аналитик.  
    В контексте доступны:  
    — исходный запрос (initial_request);  
    — результат парсинга (request_parser_agent_output);  
    — OSINT‑сводка по компаниям (osint_researcher_agent_output);  
    — идентифицированный заказчик (customer_identifier_output).)
    
    Контекст о возможностях команды Innowise:
    - Мы предоставляем зрелую экспертизу по {business_domain} и смежным технологиям;.
    - Используем AI в тестировании: predictive test selection, self-healing тесты, anomaly detection.
    - Строим автоматизацию в CI/CD, управляем тестами через observability-платформы.
    - Покрываем полный спектр задач в области {business_domain};.
    - Умеем работать со стартапами (гибкость, скорость) и крупными корпоративными проектами (устоявшиеся процессы).
    
    Твоя задача:
    
    1. Добавь БЛОК: "Тип проекта и нужный профиль специалиста":
       - Проанализируй проект: это стартап или долгосрочный корпоративный проект.
       - Учитывай домен (например, Computer Vision, FinTech, Security).
       - На основании анализа:
         - Укажи основной профиль (QA / AQA / Full-stack QA), соответствующий роли из запроса.
         - Выдели реальные требования на основе запроса (например, если указан Manual QA, не расширяй до автоматизации без явного запроса).
    
    2. Привлекательность вакансии:
       - Оцени текстово (без цифр).
       - Опиши плюсы и минусы: стек, технологии, домен проекта, зрелость процессов, влияние QA на продукт.
    
    3. Портрет идеального кандидата:
       - Hard skills: соответствующие требованиям запроса.
       - Soft skills:
         - Стартап: гибкость, самостоятельность, умение строить процессы с нуля.
         - Корпорация: системность, критичность, способность эффективно работать в существующих процессах.
       - Тип ответственности:
         - QA (ручное тестирование и тестовая документация)
         - AQA (автоматизация API, UI, интеграционных тестов)
         - Full-stack QA (баланс ручного тестирования и автоматизации)
    
    4. Специфические типичные задачи:
       - Укажи только задачи, релевантные реальному запросу и стеку.
       - Не включай базовые общие активности вроде "написание багов", "проверка фич".
    
    5. Специфические дополнительные требования:
       - Например, наличие опыта с конкретными технологиями, понимание домена проекта (например, Computer Vision), региональные требования (например, EU+Georgia).
    
    6. Добавь БЛОК: "Что может быть плюсом для проекта":
       - Аккуратно предложи навыки и опыт, которые не требуются прямо сейчас, но могут быть полезны проекту в будущем (например, навыки автоматизации тестов, опыт работы с performance/security testing, опыт CI/CD-интеграций).
    
    Формат вывода:
    - Обычный текст без JSON, скобок или меток.
    - Структурируй текст в короткие логичные абзацы и списки.
    - Соблюдай естественную и профессиональную подачу.
    
    Важно:
    - Основывай все выводы только на реальных данных из запроса и OSINT.
    - Расширение возможностей (например, про автоматизацию) указывай отдельно как "потенциальное преимущество", а не обязательное требование.
    - Сохраняй профессиональный тон и внимание к деталям.
"""
    return prompt_text
